// Regenerates stations.json and REPORT.md from the files in sources/. Run with
// `pnpm --filter @rutalibre/registry build:registry`. Fails on any issue not explained in
// config.EXPLAINED_ISSUES, so a data change can't silently degrade the registry.

import { readFileSync, writeFileSync } from 'node:fs'
import { buildRegistry, type Issue, issueKey } from './build.ts'
import { EXPLAINED_ISSUES } from './config.ts'
import { CatalogueSchema, LiveDevicesSchema, StationsFileSchema } from './schema.ts'

const root = new URL('../', import.meta.url)
const readJson = (path: string): unknown => JSON.parse(readFileSync(new URL(path, root), 'utf8'))

const catalogue = CatalogueSchema.parse(readJson('sources/metro_dispositivos.geojson'))
const live = LiveDevicesSchema.parse(readJson('sources/seguimos-devices.json'))
const { file, issues } = buildRegistry(catalogue, live)

StationsFileSchema.parse(file)
writeFileSync(new URL('stations.json', root), `${JSON.stringify(file, null, 2)}\n`)
writeFileSync(new URL('REPORT.md', root), renderReport(file.stations.length, issues))

const unexplained = issues.filter(
  (i) => i.kind !== 'station-without-elevator' && !(issueKey(i) in EXPLAINED_ISSUES),
)
const devices = file.stations.reduce((sum, s) => sum + s.devices.length, 0)
console.log(
  `stations.json: ${file.stations.length} stations, ${devices} devices, ${issues.length} issues`,
)
if (unexplained.length > 0) {
  console.error(
    `\n${unexplained.length} unexplained issue(s). Fix the data/config or explain them:`,
  )
  for (const i of unexplained) console.error(`  '${issueKey(i)}': '…', // ${i.detail}`)
  process.exit(1)
}

function renderReport(stationCount: number, list: readonly Issue[]): string {
  const rows = list.map((i) => {
    const why =
      EXPLAINED_ISSUES[issueKey(i)] ??
      (i.kind === 'station-without-elevator' ? 'informational' : '**unexplained**')
    return `| ${i.kind} | \`${i.subject}\` | ${i.detail.replaceAll('|', '\\|')} | ${why} |`
  })
  return [
    '# Station registry report',
    '',
    'Generated by `src/cli.ts` alongside `stations.json`. Do not edit by hand.',
    '',
    `- Stations: ${stationCount}`,
    `- Issues: ${list.length}`,
    '',
    '| Issue | Subject | Detail | Why it is acceptable |',
    '| ----- | ------- | ------ | -------------------- |',
    ...rows,
    '',
  ].join('\n')
}
